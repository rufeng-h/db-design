-- 按父部门查子部门
CREATE INDEX idx_sys_org_parent
    ON sys_org (parent_id) WHERE is_deleted = FALSE;

COMMENT
ON INDEX idx_sys_org_parent IS '按父部门ID查询子部门';

-- 按 full_seq 查询（比如子树查询）
CREATE INDEX idx_sys_org_full_seq
    ON sys_org (full_seq) WHERE is_deleted = FALSE;

COMMENT
ON INDEX idx_sys_org_full_seq IS '按 full_seq 查询部门树';

